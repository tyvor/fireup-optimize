'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = path.join(root, 'locales');
const extension = path.join(root, 'extension');
const check = process.argv.includes('--check');
const commandKey = 'Unload unprotected background tabs in all windows';
const read = file => JSON.parse(fs.readFileSync(file, 'utf8'));
const placeholders = text => [...new Set([...text.matchAll(/\{(\w+)\}/g)].map(match => match[1]))].sort().join(',');
const english = read(path.join(source, 'en.json'));
const catalogs = {};
const outputs = new Map();

for (const file of fs.readdirSync(source).sort()) {
  if (!file.endsWith('.json')) continue;
  const code = path.basename(file, '.json');
  if (!/^[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*$/.test(code) || Intl.getCanonicalLocales(code)[0] !== code) {
    throw new Error(`${file}: use a canonical language tag, for example fr or pt-BR`);
  }
  const { name, direction, description, messages } = read(path.join(source, file));
  if (typeof name !== 'string' || !name.trim() || !['ltr', 'rtl'].includes(direction) ||
      typeof description !== 'string' || !description.trim() || !messages || typeof messages !== 'object' || Array.isArray(messages)) {
    throw new Error(`${file}: expected name, direction, description and messages`);
  }
  for (const [key, value] of Object.entries(messages)) {
    if (!Object.hasOwn(english.messages, key)) throw new Error(`${file}: unknown message ${key}`);
    if (typeof value !== 'string' || !value.trim() || placeholders(value) !== placeholders(key)) {
      throw new Error(`${file}: check the text and placeholders for ${key}`);
    }
  }
  catalogs[code] = { name, direction, messages };
  const native = {
    extensionName: { message: 'FireUp' },
    extensionDescription: { message: description },
    unloadCommand: { message: messages[commandKey] || english.messages[commandKey] }
  };
  outputs.set(path.join(extension, '_locales', code.replaceAll('-', '_'), 'messages.json'), JSON.stringify(native, null, 2) + '\n');
}

outputs.set(path.join(extension, 'locales.generated.js'),
  '// Generated by npm run locales. Edit locales/*.json.\n' +
  'globalThis.FireUpLocales = ' + JSON.stringify(catalogs, null, 2) + ';\n' +
  "if (typeof module !== 'undefined') module.exports = globalThis.FireUpLocales;\n");

for (const [file, contents] of outputs) {
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n') !== contents) {
      throw new Error(`Stale locale output: ${path.relative(root, file)}. Run npm run locales.`);
    }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, contents);
  }
}
console.log(`${Object.keys(catalogs).length} language catalogs ${check ? 'checked' : 'generated'}.`);
