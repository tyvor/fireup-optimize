'use strict';
const { chromium } = require('playwright');
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const { harness } = require('./harness.cjs');
(async () => {
  const h = harness({ count: 6, keepRecent: 10 });
  h.tabs[0].url = 'https://chatgpt.com'; h.tabs[0].title = 'Example chat'; h.tabs[0].active = true;
  h.tabs[1].url = 'https://www.youtube.com/watch?v=example'; h.tabs[1].title = 'Example YouTube page';
  h.tabs[2].title = 'yt-dlp / yt-dlp'; h.tabs[2].discarded = true;
  h.tabs[3].url = 'https://docs.example.org'; h.tabs[3].title = 'Work notes';
  h.tabs[4].windowId = 2; h.tabs[4].url = 'https://another.example.org'; h.tabs[4].title = 'Another window';
  h.tabs[5].title = 'Release 1.3.1 · Legcord';
  await h.engine.setProtection(4, 'permanent');
  let optionsOpened = 0, failNextState = false;
  fs.mkdirSync(path.resolve('work/browser-downloads'), { recursive: true });
  const b = await chromium.launch({ headless: true, downloadsPath: path.resolve('work/browser-downloads'), ...(process.env.FIREUP_BROWSER ? { executablePath: process.env.FIREUP_BROWSER } : {}), env: { ...process.env, TEMP: path.resolve('work/browser-temp'), TMP: path.resolve('work/browser-temp') } });
  const evidence = [], errors = [];
  try {
    const page = await b.newPage({ viewport: { width: 400, height: 600 } });
    await page.exposeFunction('fireupCommand', async m => {
      switch (m.type) {
        case 'state': if (failNextState) { failNextState = false; throw Error('Test unavailable'); } return h.engine.snapshot();
        case 'local': return h.local;
        case 'get-settings': return h.engine.getSettings();
        case 'export-settings': return h.engine.exportSettings();
        case 'preview-import': return h.engine.previewImport(m.text);
        case 'import-settings': return h.engine.importSettings(m.text);
        case 'protect': return h.engine.setProtection(m.id, m.mode);
        case 'settings': return h.engine.saveSettings(m.value);
        case 'sleep': return h.engine.start(true, m.scope, m.ids);
        case 'cancel': return h.engine.cancel();
        case 'options': optionsOpened++; return true;
        case 'focus': return true;
      }
    });
    await page.addInitScript(() => {
      window.browser = { i18n: { getUILanguage: () => 'en-US' }, runtime: { sendMessage: m => window.fireupCommand(m), onMessage: { addListener() {} } },
        storage: { local: { get: () => window.fireupCommand({ type: 'local' }) } }, windows: { getCurrent: async () => ({ id: 1 }) } };
    });
    page.on('pageerror', e => { errors.push(e.message); console.error('UI page error:', e.message); });
    const file = name => 'file:///' + path.resolve(__dirname, '../extension', name).replace(/\\/g, '/');
    await page.goto(file('popup.html'));
    await page.waitForFunction(() => Boolean(document.querySelector('.tab-row')) || !document.querySelector('#retry').hidden);
    assert.equal(await page.locator('#counts').textContent(), 'Loaded 5 of 6', await page.locator('body').innerText());
    assert.equal(await page.locator('.tab-row').count(), 6);
    assert.equal(await page.locator('#sleep').textContent(), 'Unload tabs: 2');
    evidence.push('counts and current-window candidate preview');
    await page.emulateMedia({ colorScheme: 'light' });
    await page.screenshot({ path: path.resolve(__dirname, '../preview-light.png') });
    await page.emulateMedia({ colorScheme: 'dark' });
    await page.screenshot({ path: path.resolve(__dirname, '../preview-dark.png') });
    const dark = await page.evaluate(() => getComputedStyle(document.documentElement).backgroundColor);
    assert.equal(dark, 'rgb(43, 42, 51)');
    evidence.push('system light and dark themes');
    await page.locator('#search').fill('youtube'); assert.equal(await page.locator('.tab-row:visible').count(), 1);
    const protect = page.locator('.tab-row[data-id="2"] .protect');
    await protect.focus(); await page.keyboard.press('Enter'); await page.locator('[data-protect="30"]').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent === 'Protection updated.');
    assert.equal(await page.evaluate(() => document.activeElement.closest('.tab-row')?.dataset.id), '2');
    assert.equal((await h.engine.snapshot()).tabs.find(t => t.id === 2).protection.mode, 'timed');
    await protect.click(); await page.keyboard.press('Escape'); assert.equal(await page.evaluate(() => document.activeElement.className), 'protect');
    evidence.push('search, 30-minute protection, preserved keyboard focus and Escape');
    await page.locator('#search').fill('');
    await page.locator('.tab-row[data-id="6"] .choose').check(); await page.locator('#scope').selectOption('selected');
    assert.equal(await page.locator('#sleep').textContent(), 'Unload tabs: 1');
    await page.locator('#sleep').click(); await page.waitForFunction(() => document.querySelector('#cancel').hidden === false);
    await page.locator('#cancel').click(); await page.waitForFunction(() => document.querySelector('#status').textContent.includes('stopped'));
    assert.equal(h.calls.discard, 0);
    evidence.push('selected scope, queue and cancellation');
    await page.locator('#scope').selectOption('site:another.example.org'); await page.locator('#sleep').click(); await h.drain();
    await page.locator('#refresh').click(); await page.waitForFunction(() => document.querySelector('#counts').textContent === 'Loaded 4 of 6');
    assert(h.tabs[4].discarded);
    evidence.push('site scope and actual engine discard with refreshed state');
    await page.locator('#pause').click(); await page.waitForFunction(() => document.querySelector('#auto').textContent === 'Automatic sleep paused');
    await page.locator('#pause').click(); await page.waitForFunction(() => document.querySelector('#auto').textContent === 'Automatic sleep on');
    await page.locator('#filter').selectOption('sleeping'); assert.equal(await page.locator('.tab-row:visible').count(), 2);
    await page.locator('#search').fill('no-matching-tabs'); assert.match(await page.locator('.empty').textContent(), /No matches/);
    evidence.push('pause, resume, state filter and empty search');
    await page.locator('#options').click(); assert.equal(optionsOpened, 1);
    for (const width of [400, 320]) {
      await page.setViewportSize({ width, height: 600 });
      const size = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight }));
      assert(size.scroll <= size.width, JSON.stringify(size)); assert(size.height <= 600, JSON.stringify(size));
    }
    evidence.push('popup fits 400/320px and 600px height');
    await page.goto(file('options.html')); await page.locator('#settings').waitFor({ state: 'visible' });
    await page.locator('#keep').fill('8'); await page.locator('#idle').fill('15'); await page.locator('#sites').fill('chatgpt.com\ndiscord.com');
    await page.locator('#theme').selectOption('light'); await page.getByRole('button', { name: 'Save settings' }).click();
    await page.waitForFunction(() => document.querySelector('#saved').textContent === 'Settings saved.');
    assert.equal(h.local.settings.keepRecent, 8); assert.equal(h.local.settings.theme, 'light');
    await page.locator('#sites').fill('*.example.org'); await page.getByRole('button', { name: 'Save settings' }).click();
    await page.waitForFunction(() => document.querySelector('#saved').className === 'error');
    assert.equal(await page.locator('#saved').getAttribute('class'), 'error');
    assert.equal(h.local.settings.sites[0], 'chatgpt.com');
    await page.screenshot({ path: path.resolve(__dirname, '../preview-settings.png'), fullPage: true });
    evidence.push('options save, theme preview and invalid domain validation');
    await page.goto(file('popup.html')); await page.waitForFunction(() => document.querySelector('#counts').textContent.includes('of 6'));
    await page.locator('#filter').selectOption('protected');
    await page.locator('.tab-row[data-id="2"] .protect').click(); await page.locator('[data-protect="none"]').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent === 'Protection updated.');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'search');
    evidence.push('focus fallback when unprotected row disappears under filter');
    failNextState = true; await page.goto(file('popup.html')); await page.locator('#retry').waitFor({ state: 'visible' });
    assert(await page.locator('#sleep').isDisabled()); await page.locator('#retry').click();
    await page.waitForFunction(() => document.querySelector('#counts').textContent.includes('of 6'));
    assert(await page.locator('#retry').isHidden());
    evidence.push('initial error state and successful retry');
    await page.goto(file('options.html')); await page.locator('#transfer').waitFor({ state: 'visible' });
    assert(await page.locator('#anti-thrash').isChecked());
    const downloadPromise = page.waitForEvent('download'); await page.locator('#export').click();
    const download = await downloadPromise; await download.saveAs(path.resolve('work/fireup-settings-ui.json'));
    const exported = JSON.parse(fs.readFileSync('work/fireup-settings-ui.json', 'utf8'));
    assert.equal(exported.application, 'FireUp'); assert.equal(exported.appVersion, '0.4.0'); assert.equal(exported.settings.keepRecent, 8); assert.equal(exported.settings.antiThrash, true);
    assert.equal(Object.hasOwn(exported, 'tabs'), false);
    evidence.push('export downloads a valid settings-only JSON file');
    const candidate = structuredClone(exported); candidate.settings = { ...candidate.settings, keepRecent: 9, idleMinutes: 25, theme: 'dark', antiThrash: false, language: 'auto', sites: ['imported.example'], enabled: false };
    const importedFile = { name: 'fireup-settings.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(candidate)) };
    await page.locator('#import-file').setInputFiles(importedFile); await page.locator('#import-preview').waitFor({ state: 'visible' });
    assert.equal(h.local.settings.keepRecent, 8); assert.match(await page.locator('#import-summary').textContent(), /Paused/); assert.equal(await page.locator('#import-sites').inputValue(), 'imported.example');
    await page.screenshot({ path: path.resolve(__dirname, '../preview-transfer.png'), fullPage: true });
    await page.locator('#cancel-import').click(); assert(await page.locator('#import-preview').isHidden()); assert.equal(h.local.settings.keepRecent, 8);
    evidence.push('import preview lists full settings and cancellation preserves current values');
    await page.locator('#import-file').setInputFiles(importedFile); await page.locator('#import-preview').waitFor({ state: 'visible' }); await page.locator('#apply-import').click();
    await page.waitForFunction(() => document.querySelector('#transfer-status').textContent === 'Imported settings applied.');
    assert.equal(h.local.settings.keepRecent, 9); assert.equal(h.local.settings.enabled, false); assert.equal(h.local.settings.antiThrash, false); assert.equal(await page.locator('#keep').inputValue(), '9'); assert.equal(await page.locator('#anti-thrash').isChecked(), false);
    evidence.push('apply import updates backend, form, theme and anti-thrashing switch');
    await page.locator('#import-file').setInputFiles({ name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{broken') });
    await page.waitForFunction(() => document.querySelector('#transfer-status').classList.contains('error')); assert(await page.locator('#import-preview').isHidden()); assert.equal(h.local.settings.keepRecent, 9);
    await page.locator('#import-file').setInputFiles({ name: 'large.json', mimeType: 'application/json', buffer: Buffer.alloc(256 * 1024 + 1, 32) });
    await page.waitForFunction(() => document.querySelector('#transfer-status').textContent.includes('256')); assert.equal(h.local.settings.keepRecent, 9);
    await page.locator('#anti-thrash').check(); await page.getByRole('button', { name: 'Save settings' }).click();
    await page.waitForFunction(() => document.querySelector('#saved').textContent === 'Settings saved.'); assert.equal(h.local.settings.antiThrash, true);
    evidence.push('invalid and oversized imports are rejected, anti-thrashing preference can be saved');
    await page.emulateMedia({ colorScheme: 'light' }); await page.locator('#theme').selectOption('light');
    await page.screenshot({ path: path.resolve(__dirname, '../preview-settings.png'), fullPage: true });
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.resolve(__dirname, '../ui-checks.json'), JSON.stringify({ evidence, errors }, null, 2));
    console.log(JSON.stringify({ passed: evidence.length, evidence }, null, 2));
  } finally { await b.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });



